/** Початкові пункти чек-листа: свої до списку + базові + під країну. */
export const zamovchennyaCheklista = (podorozh: {
  id: string | number;
  country_code: string;
}): TochkaChek[] => {
  const mustVisit = chekListy[String(podorozh.id)];
  if (mustVisit) {
    return mustVisit.map((tekst, index) => ({
      id: index + 1,
      tekst,
      zrobleno: false,
    }));
  }
  return [
    ...bazaCheklista,
    ...(dobirZaKrayinoyu[podorozh.country_code] || []),
  ].map((tekst, index) => ({ id: index + 1, tekst, zrobleno: false }));
};
